const SHEBANG: [RegExp, LangId][] = [
  [/\b(ba|z|k|da)?sh\b/, 'bash'],
  [/\bpython[0-9.]*\b/, 'python'],
  [/\b(node|deno|bun)\b/, 'javascript'],
  [/\bperl\b/, 'perl'],
  [/\bruby\b/, 'ruby'],
  [/\b(pwsh|powershell)\b/, 'powershell'],
  [/\bphp\b/, 'php'],
  [/\blua\b/, 'lua'],
  [/\bRscript\b/, 'r'],
];

/** Language from the shebang line (`#!/usr/bin/env python3`), or null. */
export function fromShebang(firstLine: string): LangId | null {
  if (!firstLine.startsWith('#!')) return null;
  const line = firstLine.slice(2).trim();
  // `/usr/bin/env -S node --flags` → interpreter after env
  const parts = line.split(/\s+/);
  let interp = parts[0]?.split('/').pop() ?? '';
  if (interp === 'env') interp = parts.slice(1).find((p) => !p.startsWith('-')) ?? '';
  for (const [re, id] of SHEBANG) if (re.test(interp)) return id;
  return null;
}

/** Language for a git path (+ optional first line of the file). */
export function languageFor(path: string, firstLine?: string): LangId | null {
  const name = (path.split('/').pop() ?? path).toLowerCase();
  const byName = FILENAMES[name];
  if (byName) return byName;
  if (name.startsWith('dockerfile.') || name.endsWith('.dockerfile')) return 'dockerfile';
  const dot = name.lastIndexOf('.');
  if (dot >= 0) {
    const byExt = EXT[name.slice(dot + 1)];
    if (byExt) return byExt;
  }
  return firstLine !== undefined ? fromShebang(firstLine) : null;
}

/** `language-xxx` class from markdown code fences → our id (aliases like `ts`, `sh`, `toml`). */
export function languageForFence(tag: string): LangId | null {
  const t = tag.toLowerCase();
  if ((LANG_IDS as readonly string[]).includes(t)) return t as LangId;
  const alias: Record<string, LangId> = {
    shell: 'bash',
    console: 'bash',
    zsh: 'bash',
    js: 'javascript',
    ts: 'typescript',
    tsx: 'typescript',
    jsx: 'javascript',
    py: 'python',
    rb: 'ruby',
    rs: 'rust',
    toml: 'ini',
    yml: 'yaml',
    html: 'xml',
    svg: 'xml',
    'c++': 'cpp',
    'c#': 'csharp',
    cs: 'csharp',
    kt: 'kotlin',
    ps1: 'powershell',
    pwsh: 'powershell',
    md: 'markdown',
    docker: 'dockerfile',
    make: 'makefile',
    golang: 'go',
  };
  return alias[t] ?? EXT[t] ?? null;
}
